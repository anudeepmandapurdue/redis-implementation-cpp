struct Conn{
    int fd = -1;
    bool want_read = false; //represetns fd list for readiness API
    bool want_write = false; 
    bool want_close = false; //tells even loop to destroy the connection

    std::vector<uint8_t> incoming; //data to be parsed by the application 
    std::vector<uint8_t> outgoing; //responses generated by the application 
};

static void msg(const char *msg) {
    fprintf(stderr, "%s\n", msg);
}

void die(const char* msg) {
    perror(msg);
    exit(1);
}
const size_t k_max_msg = 4096; //max message size?

//reads now nonblocking so not needed but good to have
static int32_t read_full(int fd, char *buf, size_t n ){
    while (n>0){
        ssize_t rv = read(fd, buf, n);
        if(rv <= 0){
            return -1;
        }
        assert((size_t)rv <= n );
        n -= (size_t)rv;
        buf += rv;
        
    }
    return 0;
}
