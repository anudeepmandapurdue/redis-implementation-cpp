#define container_of(ptr, T, member) \
    ((T *)( (char *)ptr - offsetof(T, member) ))

const size_t k_max_msg = 32 << 20; //max message size?
const size_t k_max_args = 200 * 1000;

enum {
    RES_OK = 0,
    RES_ERR = 1,
    RES_NX = 2,
};

