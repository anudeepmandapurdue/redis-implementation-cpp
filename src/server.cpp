struct Conn{
    int fd = -1;
    bool want_read = false; //represetns fd list for readiness API
    bool want_write = false; 
    bool want_close = false; //tells even loop to destroy the connection

    std::vector<uint8_t> incoming; //data to be parsed by the application 
    std::vector<uint8_t> outgoing; //responses generated by the application 
};

//internal format for a reply,
struct Response{
    uint32_t status = 0; //returns the status in integer -> maps to differnet meanings
    std::vector<uint8_t> data; //holds teh actual value in raw byte format
};
