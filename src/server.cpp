static void msg(const char *msg) {
    fprintf(stderr, "%s\n", msg);
}

static void buf_append(std::vector<uint8_t> &buf, const uint8_t *data, size_t len){
    buf.insert(buf.end(), data, data + len); //adds at the end of the buffer
}
//remove from the front, remove n bytes
static void buf_consume(std::vector<uint8_t> &buf , size_t n){
    buf.erase(buf.begin(), buf.begin()+n);

}
static bool read_str(const uint8_t *&cur, const uint8_t *end, size_t n, std::string &out){
    if (cur + n > end){ //boundary check, cur is current poisition, end is cliff edge of valid data -> prevents a buffer over read
        return false;
    }
    out.assign((const char*)cur, n); //extracts starting at the cur address and the ending addressa and copies bytes into std::string in internal memory
    cur += n; //advance hte cursor
    return true;
}
static bool read_u32(const uint8_t *&cur, const uint8_t *end, uint32_t &out) { // safely extract 32 bit integer from byte in buffer
    if(cur + 4 > end){ //boundary check, cur is current poisition, end is cliff edge of valid data -> prevents a buffer over read
        return false;
    }

    memcpy(&out, cur, 4); //takes 4 raw bytes starting at the addrtess of cur and copies directly to memory address of out. 
    cur += 4;
    return true;

}
