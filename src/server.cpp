static int32_t parse_req(const uint8_t *data, size_t size, std::vector<std::string> &out) {
    const uint8_t *end = data + size; //pointer to end of request message?

    uint32_t nstr = 0; //index of the message
    if(!read_u32(data, end, nstr)){ //if data is too short fails
        return -1;
    }

    if(nstr > k_max_args){
        return -1; //too long fails
    }

    while(out.size() < nstr){
        uint32_t len = 0;
        if(!read_u32(data, end, len)){ // read the string length, returns the length with integer value and places it in len 
            return -1; 
        }
        out.push_back(std::string()); //convert to string 
        if (!read_str(data, end, len, out.back())) { //read actual string
            return -1;
        }
    }
    if(data != end){
        return -1; //trailing garbage
    }
    return 0;

}

static void make_response(const Response &resp, std::vector<uint8_t> &out) {
    uint32_t resp_len = 4 + (uint32_t)resp.data.size();
    buf_append(out, (const uint8_t *)&resp_len, 4);
    buf_append(out, (const uint8_t *)&resp.status, 4);
    buf_append(out, resp.data.data(), resp.data.size());
}

static uint64_t str_hash(const uint8_t *data, size_t len) {
    uint32_t h = 0x811C9DC5;
    for (size_t i = 0; i < len; i++) {
        h = (h + data[i]) * 0x01000193;
    }
    return h;
}


